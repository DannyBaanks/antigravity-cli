def passive_copy_bindings(copy_exit_action: str) -> str:
    """copy-mode-vi keys: in PASSIVE copy-mode (wheel/drag) menu keys leave the scroll and go to
    the app; in ACTIVE copy-mode (Alt+C) they keep their copy-mode meaning."""
    keys = [("Up", "send-keys -X cursor-up"), ("Down", "send-keys -X cursor-down"),
            ("Left", "send-keys -X cursor-left"), ("Right", "send-keys -X cursor-right"),
            ("Enter", copy_exit_action), ("Tab", "send-keys -X cancel ; send-keys Tab")]
    lines = [f"bind -T copy-mode-vi {k} if -F '#{{@passive_copy}}' "
             f"{{ send-keys -X cancel ; send-keys {k} }} {{ {active} }}" for k, active in keys]
    # Esc in passive mode only leaves the scroll: forwarding it would cancel AGY's menu
    lines.append("bind -T copy-mode-vi Escape if -F '#{@passive_copy}' "
                 "{ send-keys -X cancel } { send-keys -X clear-selection }")
    return "\n".join(lines)


# A hung tmux server must not hang the scanner thread: a stuck scan would keep showing the last
# session list as live with scan_failed False. load_sessions turns a timeout into a failed scan.
TMUX_TIMEOUT_SEC = 2.0
TMUX_STATE: dict[str, int] = {"timeouts": 0}


def tmux_cmd(*args: str, capture: bool = False, timeout: float | None = TMUX_TIMEOUT_SEC) -> subprocess.CompletedProcess:
    """Run tmux on the agy-dash socket. `timeout=None` only for calls that block on purpose
    (display-popup). On timeout returns rc 124 and counts it in TMUX_STATE["timeouts"]."""
    argv = ["tmux", "-L", _paths.TMUX_SOCKET, "-f", str(_paths.TMUX_CONF), *args]
    out = subprocess.PIPE if capture else subprocess.DEVNULL
    try:
        return subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=out, stderr=out, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        TMUX_STATE["timeouts"] += 1
        return subprocess.CompletedProcess(argv, 124, "", f"tmux no respondió en {timeout:g} s")


def ensure_dash_window_zero() -> None:
    self_path = _paths.SELF_PATH
    cp = tmux_cmd("list-windows", "-t", _paths.TMUX_SESSION, "-F", "#{window_index}|#{window_name}", capture=True)
    if cp.returncode != 0:
        return
    for line in cp.stdout.splitlines():
        parts = line.split("|")
        if len(parts) >= 2 and "DASH" in parts[1]:
            return
    tui_cmd = f"exec python3 {sh_quote(str(self_path))} tui"
    cp_new = tmux_cmd(
        "new-window", "-d", "-P", "-F", "#{window_index}", "-t", _paths.TMUX_SESSION, "-n", "⚡DASH", tui_cmd, capture=True
    )
    if cp_new.returncode == 0 and cp_new.stdout.strip():
        new_idx = cp_new.stdout.strip().splitlines()[-1]
        if new_idx != "0":
            tmux_cmd("swap-window", "-d", "-s", f"{_paths.TMUX_SESSION}:{new_idx}", "-t", f"{_paths.TMUX_SESSION}:0")


def _no_dash_marker(name: str) -> str:
    """Only the Command Center window may contain `DASH` (tmux formats and lookups match `*DASH*`)."""
    return re.sub(r"DASH", "Dash", name)


def _short_tab_title(title: str, prefix: str = "") -> str:
    clean = re.sub(r"[^A-Za-z0-9áéíóúÁÉÍÓÚñÑ_-]+", "-", title.strip()).strip("-")
    clean = clean[:15] or "session"
    return _no_dash_marker(f"{prefix}{clean}")


def _find_dash_window_idx() -> str:
    cp = tmux_cmd("list-windows", "-t", _paths.TMUX_SESSION, "-F", "#{window_index}|#{window_name}", capture=True)
    if cp.returncode == 0 and cp.stdout:
        for line in cp.stdout.splitlines():
            parts = line.split("|", 1)
            if len(parts) == 2 and "DASH" in parts[1]:
                return parts[0].strip()
    return "0"


def _select_dash_window() -> None:
    tmux_cmd("select-window", "-t", f"{_paths.TMUX_SESSION}:{_find_dash_window_idx()}")


def _find_tmux_window_by_conv(conv_id: str) -> str | None:
    info = _get_dash_window_map().get(conv_id)
    return info[0] if info else None


def close_session_tabs_for_deletion(conv_id: str) -> None:
    """Close any tmux window (dash or background) bound to `conv_id`, never closing 0:⚡DASH."""
    dash_info = _get_dash_window_map().get(conv_id)
    if dash_info is not None:
        win_idx, win_name = dash_info
        if "DASH" not in win_name:
            tmux_cmd("kill-window", "-t", f"{_paths.TMUX_SESSION}:{win_idx}")
    bg_info = _get_bg_window_map().get(conv_id)
    if bg_info is not None:
        tmux_cmd("kill-window", "-t", f"{_paths.TMUX_BG_SESSION}:{bg_info[0]}")


def _replace_tmux_pane_with_wake_stub(session: _sessions.AgySession) -> None:
    win_idx = _find_tmux_window_by_conv(session.conversation_id)
    if not win_idx:
        return
    self_path = _paths.SELF_PATH
    tab_name = _short_tab_title(session.title, prefix="💤")
    stub_cmd = (
        f"exec python3 {sh_quote(str(self_path))} wake-stub "
        f"{sh_quote(session.conversation_id)} --cwd {sh_quote(session.workspace)} "
        f"--title {sh_quote(session.title)}"
    )
    tmux_cmd("respawn-pane", "-k", "-t", f"{_paths.TMUX_SESSION}:{win_idx}.0", stub_cmd)
    tmux_cmd("rename-window", "-t", f"{_paths.TMUX_SESSION}:{win_idx}", tab_name)


def open_session_in_dashboard_tab(
    session: _sessions.AgySession,
    *,
    switch_to: bool = True,
    as_stub: bool = False,
    force_live_mirror: bool = False,
    force_interactive: bool = False,
    account_slot: str | None = None,
    model: str = "",
) -> str:
    self_path = _paths.SELF_PATH
    if _procs.scan_failed() and not as_stub and not force_live_mirror:
        # Without a trustworthy scan, "no process" may be a live agy: opening one more would be a second writer.
        return (
            f"⚠ No se abre '{session.title[:30]}': el escaneo de procesos falló "
            f"({_procs.SCAN_STATE.get('reason')}). Pulsa [r] para reintentar."
        )
    # If this session was parked in hidden background `agy-bg`, pop the live window right back into view!
    bg_info = _get_bg_window_map().get(session.conversation_id)
    if bg_info is not None:
        bg_idx = bg_info[0]
        tmux_cmd("move-window", "-d", "-s", f"{_paths.TMUX_BG_SESSION}:{bg_idx}", "-t", f"{_paths.TMUX_SESSION}:")
    existing_idx = _find_tmux_window_by_conv(session.conversation_id)
    cwd = session.workspace if Path(session.workspace).is_dir() else str(Path.cwd())
    reg = _accounts.load_accounts_registry()
    chosen_slot = account_slot or reg.get("conv_accounts", {}).get(session.conversation_id) or reg.get("active_slot", "primary")
    if account_slot:
        reg.setdefault("conv_accounts", {})[session.conversation_id] = chosen_slot
        _accounts.save_accounts_registry(reg)

    # If external session is busy (RUNNING / BG-TASK) and user didn't force interactive duplicate,
    # open a <3MB Real-Time Zig Live Mirror instead of spawning a stale duplicate `agy`!
    use_mirror = force_live_mirror or (
        (not as_stub) and (not force_interactive) and session.external_busy
    )

    migrated_ext = False
    if not as_stub and not use_mirror and session.proc is not None and not session.proc.in_dash:
        # Migrate an idle external copy into the dash: it must be verifiably gone BEFORE the new agy
        # opens the same conversation (two writers on one conversation corrupt its state).
        session = _sessions.refresh_session(session.conversation_id) or session  # snapshot may be seconds old
        if session.proc is not None and not session.proc.in_dash and not session.external_busy:
            ok, _why = _procs.terminate_verified(session.proc)
            if ok:
                migrated_ext = True
            else:
                use_mirror = True  # never a second writer, even with force_interactive
        elif session.proc is not None and not session.proc.in_dash:
            use_mirror = True

    model_disp, model_slug = _accounts.resolve_model_arg(model)
    slot_flag = f" --account {sh_quote(chosen_slot)}" if chosen_slot else ""
    model_flag = f" --model {sh_quote(model_slug)}" if (model and model_slug) else ""

    if as_stub:
        tab_name = _short_tab_title(session.title, prefix="💤")
        cmd = (
            f"exec python3 {sh_quote(str(self_path))} wake-stub "
            f"{sh_quote(session.conversation_id)} --cwd {sh_quote(cwd)} "
            f"--title {sh_quote(session.title)}"
        )
    elif use_mirror:
        tab_name = _short_tab_title(session.title, prefix="👁")
        cmd = (
            f"exec python3 {sh_quote(str(self_path))} mirror "
            f"{sh_quote(session.conversation_id)} --cwd {sh_quote(cwd)} "
            f"--title {sh_quote(session.title)}"
        )
    else:
        tab_prefix = f"●{chosen_slot[:3]}·" if chosen_slot != "primary" else "●"
        tab_name = _short_tab_title(session.title, prefix=tab_prefix)
        cmd = (
            f"exec python3 {sh_quote(str(self_path))} run "
            f"--conversation {sh_quote(session.conversation_id)} --cwd {sh_quote(cwd)} "
            f"--title {sh_quote(session.title)}{slot_flag}{model_flag}"
        )

    if existing_idx is not None:
        if force_interactive or force_live_mirror or account_slot or (
            not as_stub and (session.proc is None or not session.proc.in_dash or (use_mirror and "👁" not in session.dash_win_name))
        ):
            hib_reg = _sessions.load_hibernated_registry()
            if session.conversation_id in hib_reg:
                del hib_reg[session.conversation_id]
                _sessions.save_hibernated_registry(hib_reg)
            old = session.proc if (session.proc is not None and session.proc.in_dash) else None
            if old is not None and not as_stub and not use_mirror:
                # respawn-pane -k only sends SIGHUP and returns: wait for the old agy to be gone before the new
                # one opens the same conversation (max 10 s), so the two writers never overlap.
                cmd = (
                    f"for _ in $(seq 100); do kill -0 {old.pid} 2>/dev/null || break; sleep 0.1; done; "
                    f"kill -0 {old.pid} 2>/dev/null && {{ echo 'agy anterior (PID {old.pid}) sigue vivo; no se abre otra copia'; "
                    f"sleep 30; exit 1; }}; {cmd}"
                )
            tmux_cmd("respawn-pane", "-k", "-t", f"{_paths.TMUX_SESSION}:{existing_idx}.0", cmd)
            tmux_cmd("rename-window", "-t", f"{_paths.TMUX_SESSION}:{existing_idx}", tab_name)
            tmux_cmd("set-window-option", "-t", f"{_paths.TMUX_SESSION}:{existing_idx}", "@agy_account", chosen_slot)
        if switch_to:
            tmux_cmd("select-window", "-t", f"{_paths.TMUX_SESSION}:{existing_idx}")
        if account_slot:
            return f"🔀 Baton Pass -> [{chosen_slot}] ({model_disp or 'modelo actual'}) en pestaña #{existing_idx}."
        if use_mirror:
            return f"Espejo en vivo tiempo real abierto en pestaña #{existing_idx} (<3MB, sin duplicar AGY)."
        return f"Pestaña #{existing_idx} ('{session.title}') lista."

    args = ["new-window", "-P", "-F", "#{window_id}", "-t", _paths.TMUX_SESSION, "-n", tab_name, "-c", cwd]
    if not switch_to:
        args.insert(1, "-d")
    args.append(cmd)
    cp = tmux_cmd(*args, capture=True)  # -P prints the new window's id: no guessing "the last index"
    if cp.returncode == 0 and cp.stdout and cp.stdout.strip():
        last_win = cp.stdout.strip().splitlines()[-1]
        tmux_cmd("set-window-option", "-t", f"{_paths.TMUX_SESSION}:{last_win}", "@agy_conv_id", session.conversation_id)
        tmux_cmd("set-window-option", "-t", f"{_paths.TMUX_SESSION}:{last_win}", "@agy_account", chosen_slot)
    if account_slot:
        return f"🔀 Baton Pass -> '{session.title}' continuada en [{chosen_slot}] ({model_disp or 'modelo actual'})."
    if use_mirror:
        return f"Espejo en vivo tiempo real ('{session.title}') — actualiza en <0.4s desde {session.proc.tty if session.proc else 'ext'}."
    if migrated_ext:
        return f"Migrada '{session.title}' desde consola externa al Dashboard."
    return f"Abierta '{session.title}' en pestaña del Dashboard."


def launch_account_login_tab(slot: str) -> str:
    """Open an isolated tmux tab in agy-dash to sign into an additional Google account without logging out primary."""
    safe_slot = _accounts.validate_slot_name(slot)
    if safe_slot == "primary":
        return "La cuenta `primary` usa el keyring del sistema ya autenticado."
    _accounts.ensure_isolated_home(safe_slot)
    reg = _accounts.load_accounts_registry()
    reg["accounts"].setdefault(
        safe_slot,
        {
            "slot": safe_slot,
            "mode": "isolated",
            "label": f"Pro Aislada ({safe_slot})",
            "email": "",
            "authenticated": False,
            "quota": {},
            "updated_at": "",
        },
    )
    _accounts.save_accounts_registry(reg)
    self_path = _paths.SELF_PATH
    cmd = f"exec python3 {sh_quote(str(self_path))} account-login {sh_quote(safe_slot)}"
    tmux_cmd("new-window", "-t", _paths.TMUX_SESSION, "-n", f"🔑{safe_slot[:12]}", cmd)
    return f"Abierta pestaña 🔑 Login aislado para [{safe_slot}]. Completa Google OAuth en el navegador y sal (/exit)."


