def session_live_activity(
    session: _sessions.AgySession,
    activity_cache: dict[str, tuple[tuple[int, int], str]],
) -> tuple[bool, str]:
    """Return (is_busy, short_activity_label) from session state and latest transcript turn."""
    if session.hibernated:
        return (False, "0MB HIB")
    is_busy = session.state_label in ("RUNNING", "BG-TASK")
    if not is_busy:
        return (False, "IDLE")

    cid = session.conversation_id
    sig = _sessions.transcript_sig(cid)
    cached = activity_cache.get(cid)
    label = ""
    if cached and cached[0] == sig:
        label = cached[1]
    else:
        turns = _sessions.zig_tail_transcript(cid, max_turns=2, include_tools=True)
        for t in reversed(turns):
            tools = t.get("tools") or []
            if tools:
                raw_tool = str(tools[-1]).split("(", 1)[0].strip()
                label = _TOOL_LABELS.get(raw_tool, f"{raw_tool[:14]}...")
                break
            if t.get("role") == "TOOL" and t.get("content"):
                content_s = str(t["content"])
                if "Created At:" in content_s or "Tool is running" in content_s or "background task" in content_s:
                    label = "Task running..."
                else:
                    clean_c = content_s.replace("🔧", "").strip(" \"'")[:16]
                    label = clean_c or "Task running..."
                break
        activity_cache[cid] = (sig, label)

    if not label and session.proc and session.proc.active_children:
        label = f"Running {session.proc.active_children[0][:10]}..."
    return (True, label or "Working...")


def format_led_tab_title(
    session: _sessions.AgySession,
    tick_idx: int,
    activity_text: str,
    busy: bool,
    width: int = 16,
) -> str:
    """Build a compact LED-marquee tab label with left-side Braille spinner dots when busy."""
    clean_title = re.sub(r"[^A-Za-z0-9áéíóúÁÉÍÓÚñÑ_-]+", "-", session.title.strip()).strip("-") or "session"
    clean_title = _no_dash_marker(clean_title)
    activity_text = _no_dash_marker(activity_text)
    if session.hibernated:
        return f"💤{clean_title[:width - 2]}"
    is_mirror = "👁" in session.dash_win_name
    if not busy:
        prefix = "👁" if is_mirror else "●"
        return f"{prefix}{clean_title[:width - 1]}"

    spin = _SPINNER_FRAMES[tick_idx % len(_SPINNER_FRAMES)]
    prefix = f"{spin}{'👁' if is_mirror else ''}"
    slot_w = max(8, width - len(prefix))
    tape = f"{clean_title[:22]} · {activity_text} · "
    if len(tape) <= slot_w:
        body = tape
    else:
        offset = tick_idx % len(tape)
        doubled = tape + tape
        body = doubled[offset : offset + slot_w]
    return f"{prefix}{body}"


def _tab_titles_file() -> Path:
    return _paths.COMPACTED_DIR / ".tab_titles.json"


def remember_tab_title(tab_name: str, title: str) -> None:
    """The compaction renames a tab to a short `🗜Tema-trunc`; the LED thread sees that as a
    hand rename and would save the truncated name as the title. Leave the full title for it."""
    f = _tab_titles_file()
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        with _paths.file_lock(f):
            try:
                cur = json.loads(f.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                cur = {}
            if not isinstance(cur, dict):
                cur = {}
            cur[tab_name] = title
            _paths.atomic_write_text(f, json.dumps(cur, ensure_ascii=False, indent=2))
    except OSError:
        pass


def take_tab_title(tab_name: str) -> str:
    """Full title the compaction left for ``tab_name`` (consumed), or ""."""
    f = _tab_titles_file()
    if not f.is_file():
        return ""
    try:
        with _paths.file_lock(f):
            cur = json.loads(f.read_text(encoding="utf-8"))
            if not isinstance(cur, dict) or tab_name not in cur:
                return ""
            title = str(cur.pop(tab_name) or "")
            _paths.atomic_write_text(f, json.dumps(cur, ensure_ascii=False, indent=2))
            return title
    except (OSError, ValueError):
        return ""


def _is_led_generated_name(name: str) -> bool:
    if not name:
        return True
    return name.startswith(_SPINNER_FRAMES) or name.startswith(("●", "👁", "💤", "🔑", "⚡"))


def sync_led_tmux_tabs(
    sessions: list[_sessions.AgySession],
    tick_idx: int,
    last_tab_names: dict[str, str],
    activity_cache: dict[str, tuple[tuple[int, int], str]],
) -> list[tuple[str, str]]:
    """Update open tmux tab names with animated spinner + LED action marquee, respecting user rename-window.

    Runs on the LED thread: it never mutates the sessions it gets (they are the UI's objects) nor
    writes titles to disk. A tab the user renamed by hand (`Ctrl+B ,`) is returned as
    (conversation_id, title); the caller persists it and updates its sessions on its own thread."""
    cmds: list[str] = []
    renames: list[tuple[str, str]] = []
    for s in sessions:
        if s.dash_win_idx is None:
            continue
        if s.dash_win_name.startswith("🔑"):
            continue
        prev = last_tab_names.get(s.dash_win_idx)
        view = s
        if (
            prev is not None
            and s.dash_win_name
            and s.dash_win_name != prev
            and not _is_led_generated_name(s.dash_win_name)
        ):
            title = take_tab_title(s.dash_win_name) or s.dash_win_name.strip()
            renames.append((s.conversation_id, title))
            view = _copy.copy(s)  # this tick's label already shows the new title
            view.title = title

        busy, act_txt = session_live_activity(view, activity_cache)
        new_name = format_led_tab_title(view, tick_idx, act_txt, busy)
        if prev != new_name:
            last_tab_names[s.dash_win_idx] = new_name
            cmds.extend(["rename-window", "-t", f"{_paths.TMUX_SESSION}:{s.dash_win_idx}", new_name, ";"])
    if cmds:
        tmux_cmd(*cmds[:-1])
    return renames


def _ensure_bg_session() -> None:
    has = tmux_cmd("has-session", "-t", _paths.TMUX_BG_SESSION, capture=True)
    if has.returncode != 0:
        tmux_cmd("new-session", "-d", "-s", _paths.TMUX_BG_SESSION, "-n", "_bg_anchor", "sleep infinity")


def close_tab_safely(win_idx: str) -> str:
    """Close a tab (`×`), parking RUNNING/BG-TASK sessions into hidden `agy-bg` instead of killing them."""
    cp = tmux_cmd(
        "display-message",
        "-p",
        "-t",
        win_idx if win_idx.startswith("@") else f"{_paths.TMUX_SESSION}:{win_idx}",
        "#{window_index}|#{window_name}|#{@agy_conv_id}|#{pane_current_command}|#{pane_pid}",
        capture=True,
    )
    if cp.returncode != 0 or not cp.stdout.strip():
        return f"Pestaña #{win_idx} ya no existe."
    # The status bar passes a stable window id (@N): with renumber-windows on, an index could name another tab.
    win_idx, _, rest = cp.stdout.strip().partition("|")
    parts = rest.split("|", 3)
    win_name = parts[0] if len(parts) > 0 else ""
    conv_id = parts[1].strip() if len(parts) > 1 else ""
    pane_cmd = parts[2].strip() if len(parts) > 2 else ""
    pane_pid = int(parts[3].strip()) if len(parts) > 3 and parts[3].strip().isdigit() else 0

    if "DASH" in win_name:
        return "No se cierra la pestaña principal ⚡DASH."

    # Live mirrors, wake stubs, and OAuth login helpers can close UI tab directly without affecting background AGY
    if any(ch in win_name for ch in ("👁", "💤", "🔑")) or pane_cmd == "python3":
        tmux_cmd("kill-window", "-t", f"{_paths.TMUX_SESSION}:{win_idx}")
        return f"Pestaña '{win_name}' cerrada (solo vista)."

    _, _, sessions = _sessions.load_sessions(limit=50)
    sess = next(
        (
            s
            for s in sessions
            if (conv_id and s.conversation_id == conv_id)
            or s.dash_win_idx == win_idx
            or (pane_pid and s.proc and (s.proc.pid == pane_pid or s.proc.ppid == pane_pid))
        ),
        None,
    )
    is_busy = bool(sess and sess.state_label in ("RUNNING", "BG-TASK", "UNKNOWN"))
    if is_busy:
        if sess and not conv_id:
            tmux_cmd("set-window-option", "-t", f"{_paths.TMUX_SESSION}:{win_idx}", "@agy_conv_id", sess.conversation_id)
        _ensure_bg_session()
        tmux_cmd("move-window", "-d", "-s", f"{_paths.TMUX_SESSION}:{win_idx}", "-t", f"{_paths.TMUX_BG_SESSION}:")
        return f"'{sess.title if sess else win_name}' ocultada en segundo plano (sigue trabajando viva)."

    tmux_cmd("kill-window", "-t", f"{_paths.TMUX_SESSION}:{win_idx}")
    return f"Pestaña '{win_name}' cerrada en IDLE (reabrible desde 0:⚡DASH)."
