def sh_quote(s: str) -> str:
    return "'" + s.replace("'", "'\"'\"'") + "'"


def tmux_dquote(s: str) -> str:
    """Quote a command string cleanly inside tmux `{ ... }` / double quotes."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


